def load_memory():

    if not os.path.exists(MEMORY_FILE):

        memory = {
            "raccoon": {},
            "user_preferences": {},
            "analysis_rules": {},
            "memory_policy": {},
            "portfolio_history": [],
            "important_events": [],
            "previous_decisions": []
        }

        save_json(
            MEMORY_FILE,
            memory
        )

        return memory

    return load_json(
        MEMORY_FILE
    )


# ============================================================
# 분석 결과 저장
# ============================================================

def save_analysis_history(result):

    os.makedirs(
        ANALYSIS_HISTORY_DIR,
        exist_ok=True
    )

    timestamp = datetime.now().strftime(
        "%Y%m%d_%H%M%S"
    )

    filename = (
        f"analysis_{timestamp}.md"
    )

    path = os.path.join(
        ANALYSIS_HISTORY_DIR,
        filename
    )

    with open(
        path,
        "w",
        encoding="utf-8"
    ) as f:

        f.write(result)

    return path


