# 메모리에 이번 분석 기록 추가
# ============================================================

def update_memory(
    memory,
    portfolio,
    result
):

    timestamp = datetime.now().strftime(
        "%Y-%m-%d %H:%M:%S"
    )

    # --------------------------------------------------------
    # 포트폴리오 핵심 정보 기록
    # --------------------------------------------------------

    portfolio_snapshot = {
        "timestamp": timestamp,
        "portfolio": portfolio
    }

    history = memory.setdefault(
        "portfolio_history",
        []
    )

    history.append(
        portfolio_snapshot
    )

    # 최근 30개까지만 유지
    if len(history) > 30:

        memory["portfolio_history"] = (
            history[-30:]
        )


    # --------------------------------------------------------
    # 이전 분석 기록
    # --------------------------------------------------------

    previous_decisions = memory.setdefault(
        "previous_decisions",
        []
    )

    previous_decisions.append({
        "timestamp": timestamp,
        "summary": result
    })

    # 최근 20개 분석만 유지
    if len(previous_decisions) > 20:

        memory["previous_decisions"] = (
            previous_decisions[-20:]
        )


    save_json(
        MEMORY_FILE,
        memory
    )


