# ============================================================
# 계좌 데이터에서 특정 종목 찾기
# ============================================================

def find_holding(
    portfolio_context,
    ticker
):

    if not portfolio_context or not ticker or str(ticker).upper() in ["PORTFOLIO", "ALL", "NONE"]:
        return None

    items = (
        portfolio_context
        .get("holdings", {})
        .get("result", {})
        .get("items", [])
    )

    for item in items:

        if str(
            item.get("symbol", "")
        ).upper() == str(ticker).upper():

            return item

    return None


