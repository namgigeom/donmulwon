def save_analysis_history(
    ticker,
    result
):

    os.makedirs(
        ANALYSIS_HISTORY_DIR,
        exist_ok=True
    )

    timestamp = datetime.now().strftime(
        "%Y%m%d_%H%M%S"
    )

    # ✅ ticker 예외 처리 (None 또는 빈 문자열 대비)
    safe_ticker = ticker if ticker else "PORTFOLIO"

    filename = (
        f"raccoon_{safe_ticker}_{timestamp}.md"
    )

    path = os.path.join(
        ANALYSIS_HISTORY_DIR,
        filename
    )

    with open(
        path,
        "w",
        encoding="utf-8"
    ) as f:

        f.write(result)

    return path


