def get_market_context():

    tickers = {
        "S&P500": "^GSPC",
        "NASDAQ": "^IXIC",
        "VIX": "^VIX"
    }

    result = {}

    for name, ticker in tickers.items():

        try:

            data = yf.download(
                ticker,
                period="3mo",
                interval="1d",
                auto_adjust=False,
                progress=False
            )

            if data.empty:
                continue

            close = data["Close"]

            if hasattr(close, "columns"):
                close = close.iloc[:, 0]

            current = float(close.iloc[-1])

            previous = float(close.iloc[-2])

            change = (
                (current - previous)
                / previous
                * 100
            )

            result[name] = {
                "ticker": ticker,
                "current": current,
                "daily_change_percent": change
            }

        except Exception as e:

            result[name] = {
                "error": str(e)
            }

    return result


