# 특정 종목 가격 정보
# ============================================================

def get_stock_data(
    ticker
):

    if not ticker or ticker.upper() in ["PORTFOLIO", "ALL", "NONE"]:
        return {}

    try:

        data = yf.download(
            ticker,
            period="6mo",
            interval="1d",
            auto_adjust=False,
            progress=False
        )

        if data.empty:

            return {

                "error":
                    "가격 데이터를 찾을 수 없습니다."

            }

        close = data["Close"]

        if hasattr(
            close,
            "columns"
        ):

            close = close.iloc[:, 0]

        current = float(
            close.iloc[-1]
        )

        ma20 = float(
            close.rolling(20)
            .mean()
            .iloc[-1]
        )

        ma50 = float(
            close.rolling(50)
            .mean()
            .iloc[-1]
        )

        six_month_return = (

            (
                current
                - float(close.iloc[0])
            )
            / float(close.iloc[0])
            * 100

        )

        return {

            "ticker":
                ticker.upper(),

            "current_price":
                current,

            "MA20":
                ma20,

            "MA50":
                ma50,

            "six_month_return_percent":
                six_month_return

        }

    except Exception as e:

        return {

            "error":
                str(e)

        }


