# ============================================================
# JSON 불러오기
# ============================================================

def load_json(path):

    if not os.path.exists(path):
        return {}

    try:

        with open(
            path,
            "r",
            encoding="utf-8"
        ) as f:

            return json.load(f)

    except Exception as e:

        return {
            "error": f"JSON 파일을 읽을 수 없습니다: {e}"
        }


# ============================================================
# 최근 AI 분석 파일 찾기
# ============================================================

def get_latest_analysis(prefix):

    if not os.path.exists(
        ANALYSIS_HISTORY_DIR
    ):
        return None

    files = glob.glob(
        os.path.join(
            ANALYSIS_HISTORY_DIR,
            f"{prefix}_*.md"
        )
    )

    if not files:
        return None

    files.sort(
        key=os.path.getmtime,
        reverse=True
    )

    return files[0]


# ============================================================
# AI 분석 파일 읽기
# ============================================================

def read_analysis(prefix):

    path = get_latest_analysis(
        prefix
    )

    if not path:

        return {
            "file": None,
            "content":
                "아직 해당 AI의 분석 결과가 없습니다."
        }

    try:

        with open(
            path,
            "r",
            encoding="utf-8"
        ) as f:

            content = f.read()

        return {
            "file": path,
            "content": content
        }

    except Exception as e:

        return {
            "file": path,
            "content":
                f"분석 파일을 읽을 수 없습니다: {e}"
        }


# ============================================================
# 팀원 분석 가져오기
